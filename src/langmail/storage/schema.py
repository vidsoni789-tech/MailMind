"""PersonalMail AI — Database schema and migrations.

Implements all tables specified in new_update/data-model.md while preserving
full backward compatibility with existing ~/.langmail/gmail.db tables.
"""

SCHEMA_SQL = """
-- Core email metadata (Gmail remains source of truth)
CREATE TABLE IF NOT EXISTS messages (
    message_id      TEXT PRIMARY KEY,
    thread_id       TEXT NOT NULL,
    subject         TEXT,
    snippet         TEXT,
    from_email      TEXT NOT NULL,
    from_name       TEXT,
    to_emails       TEXT,
    cc_emails       TEXT,
    date            TEXT NOT NULL,
    labels          TEXT,
    is_sent         INTEGER DEFAULT 0,
    is_read         INTEGER DEFAULT 1,
    has_attachment  INTEGER DEFAULT 0,
    size_bytes      INTEGER DEFAULT 0,
    category        TEXT DEFAULT 'other',
    priority        TEXT DEFAULT 'medium',
    requires_reply  INTEGER DEFAULT 0,
    security_risk   TEXT DEFAULT 'safe',
    triage_reason   TEXT
);

-- Contact tracking and relationship index
CREATE TABLE IF NOT EXISTS contacts (
    email           TEXT PRIMARY KEY,
    name            TEXT,
    domain          TEXT,
    first_seen      TEXT,
    last_seen       TEXT,
    message_count   INTEGER DEFAULT 0,
    sent_count      INTEGER DEFAULT 0,
    received_count  INTEGER DEFAULT 0,
    relationship    TEXT DEFAULT 'rare',
    category        TEXT DEFAULT 'unknown',
    preferred_tone  TEXT DEFAULT 'default',
    notes           TEXT
);

-- Thread summaries generated by AI
CREATE TABLE IF NOT EXISTS thread_summaries (
    thread_id       TEXT PRIMARY KEY,
    contact_email   TEXT,
    subject         TEXT,
    message_count   INTEGER,
    summary         TEXT,
    decisions       TEXT,
    requests        TEXT,
    deadlines       TEXT,
    next_steps      TEXT,
    last_updated    TEXT,
    status          TEXT DEFAULT 'active'
);

-- User profile settings (for personalization)
CREATE TABLE IF NOT EXISTS user_profiles (
    id                   INTEGER PRIMARY KEY CHECK (id = 1),
    role                 TEXT DEFAULT 'Professional',
    organization         TEXT DEFAULT '',
    college              TEXT DEFAULT '',
    bio                  TEXT DEFAULT '',
    signature            TEXT DEFAULT '',
    preferred_language   TEXT DEFAULT 'English',
    default_tone         TEXT DEFAULT 'professional',
    default_reply_length TEXT DEFAULT 'concise',
    created_at           TEXT NOT NULL,
    updated_at           TEXT NOT NULL
);

-- Extracted tasks and commitments
CREATE TABLE IF NOT EXISTS tasks (
    id              TEXT PRIMARY KEY,
    thread_id       TEXT NOT NULL,
    message_id      TEXT,
    title           TEXT NOT NULL,
    deadline        TEXT,
    priority        TEXT DEFAULT 'medium',
    status          TEXT DEFAULT 'pending',
    source_from     TEXT,
    source_text     TEXT,
    created_at      TEXT NOT NULL,
    updated_at      TEXT NOT NULL
);

-- AI generation and drafts tracking
CREATE TABLE IF NOT EXISTS drafts (
    id              TEXT PRIMARY KEY,
    thread_id       TEXT,
    gmail_draft_id  TEXT,
    to_email        TEXT NOT NULL,
    subject         TEXT NOT NULL,
    body            TEXT NOT NULL,
    status          TEXT DEFAULT 'generated',
    generation_id   TEXT,
    created_at      TEXT NOT NULL,
    updated_at      TEXT NOT NULL
);

-- AI Generation audit records
CREATE TABLE IF NOT EXISTS generations (
    id                  TEXT PRIMARY KEY,
    draft_id            TEXT,
    intent              TEXT,
    model               TEXT,
    prompt_version      TEXT,
    input_context_hash  TEXT,
    latency_ms          INTEGER,
    status              TEXT DEFAULT 'success',
    created_at          TEXT NOT NULL
);

-- User edits on drafts for edit-learning
CREATE TABLE IF NOT EXISTS user_edits (
    id              TEXT PRIMARY KEY,
    generation_id   TEXT,
    draft_id        TEXT,
    original_text   TEXT NOT NULL,
    edited_text     TEXT NOT NULL,
    diff_summary    TEXT,
    created_at      TEXT NOT NULL
);

-- Learned writing preferences
CREATE TABLE IF NOT EXISTS style_preferences (
    id              TEXT PRIMARY KEY,
    contact_email   TEXT,
    type            TEXT NOT NULL,
    value           TEXT NOT NULL,
    confidence      REAL DEFAULT 0.5,
    evidence_count  INTEGER DEFAULT 1,
    source          TEXT DEFAULT 'user_edit',
    created_at      TEXT NOT NULL,
    updated_at      TEXT NOT NULL
);

-- Local file index for smart attachment agent
CREATE TABLE IF NOT EXISTS file_index (
    id              TEXT PRIMARY KEY,
    file_path       TEXT NOT NULL UNIQUE,
    filename        TEXT NOT NULL,
    mime_type       TEXT,
    size_bytes      INTEGER,
    modified_at     TEXT,
    tags            TEXT,
    directory_path  TEXT,
    is_current      INTEGER DEFAULT 1
);

-- Connected local directories/folders for attachment indexing
CREATE TABLE IF NOT EXISTS connected_directories (
    id              TEXT PRIMARY KEY,
    dir_path        TEXT NOT NULL UNIQUE,
    label           TEXT,
    is_active       INTEGER DEFAULT 1,
    last_scanned_at TEXT,
    file_count      INTEGER DEFAULT 0,
    created_at      TEXT NOT NULL
);

-- Audit logs for human-in-the-loop actions
CREATE TABLE IF NOT EXISTS audit_logs (
    id              TEXT PRIMARY KEY,
    action          TEXT NOT NULL,
    target_type     TEXT NOT NULL,
    target_id       TEXT,
    approval_status TEXT NOT NULL,
    result          TEXT,
    created_at      TEXT NOT NULL
);

-- Performance indices
CREATE INDEX IF NOT EXISTS idx_messages_thread     ON messages(thread_id);
CREATE INDEX IF NOT EXISTS idx_messages_from       ON messages(from_email);
CREATE INDEX IF NOT EXISTS idx_messages_date       ON messages(date);
CREATE INDEX IF NOT EXISTS idx_messages_category   ON messages(category);
CREATE INDEX IF NOT EXISTS idx_messages_priority   ON messages(priority);
CREATE INDEX IF NOT EXISTS idx_contacts_domain     ON contacts(domain);
CREATE INDEX IF NOT EXISTS idx_tasks_status        ON tasks(status);
CREATE INDEX IF NOT EXISTS idx_tasks_deadline      ON tasks(deadline);
CREATE INDEX IF NOT EXISTS idx_drafts_thread       ON drafts(thread_id);
CREATE INDEX IF NOT EXISTS idx_prefs_contact       ON style_preferences(contact_email);
"""


def run_migrations(conn) -> None:
    """Run migrations to ensure new columns exist in existing tables."""
    from datetime import datetime, timezone
    from pathlib import Path
    import uuid

    cursor = conn.cursor()
    cursor.executescript(SCHEMA_SQL)

    # Check for new columns in messages (in case database was created under older schema)
    cursor.execute("PRAGMA table_info(messages)")
    msg_cols = {row["name"] for row in cursor.fetchall()}
    
    new_msg_cols = [
        ("category", "TEXT DEFAULT 'other'"),
        ("priority", "TEXT DEFAULT 'medium'"),
        ("requires_reply", "INTEGER DEFAULT 0"),
        ("security_risk", "TEXT DEFAULT 'safe'"),
        ("triage_reason", "TEXT"),
    ]
    for col_name, col_def in new_msg_cols:
        if col_name not in msg_cols:
            cursor.execute(f"ALTER TABLE messages ADD COLUMN {col_name} {col_def}")

    # Check for new columns in contacts
    cursor.execute("PRAGMA table_info(contacts)")
    contact_cols = {row["name"] for row in cursor.fetchall()}
    
    new_contact_cols = [
        ("preferred_tone", "TEXT DEFAULT 'default'"),
        ("notes", "TEXT"),
    ]
    for col_name, col_def in new_contact_cols:
        if col_name not in contact_cols:
            cursor.execute(f"ALTER TABLE contacts ADD COLUMN {col_name} {col_def}")

    # Check for directory_path column in file_index
    cursor.execute("PRAGMA table_info(file_index)")
    file_cols = {row["name"] for row in cursor.fetchall()}
    if "directory_path" not in file_cols:
        cursor.execute("ALTER TABLE file_index ADD COLUMN directory_path TEXT")

    cursor.execute("CREATE INDEX IF NOT EXISTS idx_file_dir ON file_index(directory_path)")


    # Seed default ~/.langmail/files directory into connected_directories if none exist
    cursor.execute("SELECT COUNT(*) AS count FROM connected_directories")
    row = cursor.fetchone()
    if row and row["count"] == 0:
        default_dir = Path.home() / ".langmail" / "files"
        default_dir.mkdir(parents=True, exist_ok=True)
        now = datetime.now(timezone.utc).isoformat()
        cursor.execute(
            """
            INSERT OR IGNORE INTO connected_directories (
                id, dir_path, label, is_active, last_scanned_at, file_count, created_at
            ) VALUES (?, ?, ?, 1, ?, 0, ?)
            """,
            (str(uuid.uuid4()), str(default_dir.resolve()), "PersonalMail Default Directory", now, now)
        )

    conn.commit()

